import { createHash } from 'node:crypto'
import { appendFile, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const FUNCTIONS_ROOT = path.join(ROOT, 'supabase/functions')
const METADATA_PATH = path.join(FUNCTIONS_ROOT, '_shared/releaseMetadata.ts')
const CONFIG_PATH = path.join(ROOT, 'supabase/config.toml')
const DENO_LOCK_PATH = path.join(ROOT, 'deno.lock')
export const EDGE_DEPLOYMENT_INPUTS = Object.freeze([CONFIG_PATH, DENO_LOCK_PATH])

const fullSha = (value) => typeof value === 'string' && /^[a-f0-9]{40}$/i.test(value)

const listFiles = async (directory) => (await Promise.all(
  (await readdir(directory, { withFileTypes: true })).map(async (entry) => {
    const target = path.join(directory, entry.name)
    return entry.isDirectory() ? listFiles(target) : [target]
  }),
)).flat()

const localDependency = (sourcePath, specifier) => {
  if (!specifier.startsWith('.')) return null
  return path.resolve(path.dirname(sourcePath), specifier)
}

const localDependencyClosure = async (roots, metadataPath) => {
  const pending = [...roots]
  const files = new Set()
  while (pending.length > 0) {
    const file = pending.pop()
    if (files.has(file) || path.resolve(file) === path.resolve(metadataPath)) continue
    files.add(file)
    const source = await readFile(file, 'utf8')
    for (const imported of ts.preProcessFile(source, true, true).importedFiles) {
      const dependency = localDependency(file, imported.fileName)
      if (dependency?.endsWith('.ts')) pending.push(dependency)
    }
  }
  return [...files]
}

export const edgeArtifactFiles = async ({ functionsRoot = FUNCTIONS_ROOT, metadataPath = METADATA_PATH } = {}) => {
  const roots = (await listFiles(functionsRoot))
    .filter((file) => file.endsWith('.ts'))
    .filter((file) => !file.endsWith('.test.ts'))
    .filter((file) => path.resolve(file) !== path.resolve(metadataPath))
  return (await localDependencyClosure(roots, metadataPath)).sort()
}

export const digestEdgeArtifact = async ({
  functionsRoot = FUNCTIONS_ROOT,
  metadataPath = METADATA_PATH,
  artifactRoot = functionsRoot === FUNCTIONS_ROOT ? ROOT : path.dirname(functionsRoot),
  deploymentInputPaths = functionsRoot === FUNCTIONS_ROOT ? EDGE_DEPLOYMENT_INPUTS : [],
} = {}) => {
  const files = await edgeArtifactFiles({ functionsRoot, metadataPath })
  if (files.length === 0) throw new Error('Edge release provenance requires deployable TypeScript sources')
  const hash = createHash('sha256')
  for (const file of [...files, ...deploymentInputPaths].sort()) {
    hash.update(path.relative(artifactRoot, file).split(path.sep).join('/'))
    hash.update('\0')
    hash.update(await readFile(file))
    hash.update('\0')
  }
  return hash.digest('hex')
}

export const stampEdgeReleaseProvenance = async ({
  commitSha = process.env.PANCAKE_RELEASE_SHA || process.env.GITHUB_SHA,
  functionsRoot = FUNCTIONS_ROOT,
  metadataPath = METADATA_PATH,
  artifactRoot = functionsRoot === FUNCTIONS_ROOT ? ROOT : path.dirname(functionsRoot),
  deploymentInputPaths = functionsRoot === FUNCTIONS_ROOT ? EDGE_DEPLOYMENT_INPUTS : [],
} = {}) => {
  if (!fullSha(commitSha)) throw new Error('Edge release provenance requires a full commit SHA')
  const edgeArtifactDigest = await digestEdgeArtifact({ functionsRoot, metadataPath, artifactRoot, deploymentInputPaths })
  const metadata = [
    '// Generated by scripts/stamp-edge-release-provenance.mjs. Do not edit.',
    `export const RELEASE_COMMIT_SHA = '${commitSha.toLowerCase()}'`,
    `export const EDGE_ARTIFACT_DIGEST = '${edgeArtifactDigest}'`,
    '',
  ].join('\n')
  await writeFile(metadataPath, metadata)
  return { commitSha: commitSha.toLowerCase(), edgeArtifactDigest }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const marker = await stampEdgeReleaseProvenance()
  if (process.env.GITHUB_OUTPUT) {
    await appendFile(process.env.GITHUB_OUTPUT, `edge_artifact_digest=${marker.edgeArtifactDigest}\n`)
  }
  console.log(JSON.stringify(marker))
}
