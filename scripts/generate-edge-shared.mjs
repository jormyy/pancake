import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import ts from 'typescript'

const ROOT = path.resolve(import.meta.dirname, '..')
const CHECK = process.argv.includes('--check')
const HEADER = '// Generated by scripts/generate-edge-shared.mjs. Do not edit manually.\n\n'

const read = (rel) => readFile(path.join(ROOT, rel), 'utf8')

function assertNoBackendImports(rel, contents) {
  const forbidden = [
    "from '../",
    'from "../',
    "from '@/",
    'from "@/',
    "from '@pancake/core'",
    'from "@pancake/core"',
  ]
  const hit = forbidden.find((fragment) => contents.includes(fragment))
  if (hit) throw new Error(`${rel} contains non-Edge import fragment ${hit}`)
}

function sourceFileFor(source, label) {
  return ts.createSourceFile(`${label}.ts`, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
}

function applyReplacements(source, replacements) {
  return replacements
    .sort((a, b) => b.start - a.start)
    .reduce(
      (next, replacement) => `${next.slice(0, replacement.start)}${replacement.text}${next.slice(replacement.end)}`,
      source,
    )
}

function rewriteImportDeclarations(source, label, importMap) {
  const sourceFile = sourceFileFor(source, label)
  const used = new Set()
  const replacements = []

  sourceFile.forEachChild((node) => {
    if (!ts.isImportDeclaration(node) || !ts.isStringLiteral(node.moduleSpecifier)) return
    const specifier = node.moduleSpecifier.text
    const replacement = importMap[specifier]
    if (replacement) {
      used.add(specifier)
      replacements.push({
        start: node.moduleSpecifier.getStart(sourceFile) + 1,
        end: node.moduleSpecifier.getEnd() - 1,
        text: replacement,
      })
      return
    }

    if (specifier.startsWith('.') || specifier.startsWith('@/') || specifier.startsWith('@pancake/')) {
      throw new Error(`Cannot generate ${label}: unmapped source import ${specifier}`)
    }
  })

  const missing = Object.keys(importMap).filter((specifier) => !used.has(specifier))
  if (missing.length > 0) {
    throw new Error(`Cannot generate ${label}: missing expected source imports: ${missing.join(', ')}`)
  }

  return applyReplacements(source, replacements)
}

function dropImportDeclaration(source, label, specifier) {
  const sourceFile = sourceFileFor(source, label)
  let removed = false
  const replacements = []

  sourceFile.forEachChild((node) => {
    if (!ts.isImportDeclaration(node) || !ts.isStringLiteral(node.moduleSpecifier)) return
    if (node.moduleSpecifier.text !== specifier) return
    removed = true
    const lineEnd = source.indexOf('\n', node.getEnd())
    replacements.push({
      start: node.getFullStart(),
      end: lineEnd === -1 ? node.getEnd() : lineEnd + 1,
      text: '',
    })
  })

  if (!removed) {
    throw new Error(`Cannot generate ${label}: missing expected source import ${specifier}`)
  }

  const rewritten = applyReplacements(source, replacements)
  return rewritten.startsWith('\n') ? rewritten.slice(1) : rewritten
}

function pruneEdgeExports(source, label, privateNames, removedNames = []) {
  const sourceFile = sourceFileFor(source, label)
  const replacements = []
  sourceFile.forEachChild(node => {
    const name = ts.isVariableStatement(node)
      ? node.declarationList.declarations[0]?.name.getText(sourceFile)
      : ts.isFunctionDeclaration(node) || ts.isClassDeclaration(node) || ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node) || ts.isEnumDeclaration(node)
        ? node.name?.getText(sourceFile)
        : undefined
    if (removedNames.includes(name)) {
      replacements.push({ start: node.getFullStart(), end: node.getEnd(), text: '' })
    } else if (privateNames.includes(name)) {
      const modifier = (ts.canHaveModifiers(node) ? ts.getModifiers(node) : undefined)?.find(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)
      if (!modifier) throw new Error(`Cannot generate ${label}: ${name} is not exported`)
      replacements.push({ start: modifier.getStart(sourceFile), end: modifier.getEnd() + 1, text: '' })
    }
  })
  return applyReplacements(source, replacements)
}

async function writeGenerated(rel, contents) {
  const filePath = path.join(ROOT, rel)
  const current = await read(rel).catch(() => null)
  if (current === contents) return false
  if (CHECK) {
    console.error(`${rel} is out of date. Run npm run generate:edge-shared.`)
    process.exitCode = 1
    return true
  }
  await writeFile(filePath, contents)
  return true
}

