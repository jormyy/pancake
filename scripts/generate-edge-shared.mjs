import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import ts from 'typescript'

const ROOT = path.resolve(import.meta.dirname, '..')
const CHECK = process.argv.includes('--check')
const HEADER = '// Generated by scripts/generate-edge-shared.mjs. Do not edit manually.\n\n'

const read = (rel) => readFile(path.join(ROOT, rel), 'utf8')

function assertNoBackendImports(rel, contents) {
  const forbidden = [
    "from '../",
    'from "../',
    "from '@/",
    'from "@/',
    "from '@pancake/core'",
    'from "@pancake/core"',
  ]
  const hit = forbidden.find((fragment) => contents.includes(fragment))
  if (hit) throw new Error(`${rel} contains non-Edge import fragment ${hit}`)
}

function sourceFileFor(source, label) {
  return ts.createSourceFile(`${label}.ts`, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
}

function applyReplacements(source, replacements) {
  return replacements
    .sort((a, b) => b.start - a.start)
    .reduce(
      (next, replacement) => `${next.slice(0, replacement.start)}${replacement.text}${next.slice(replacement.end)}`,
      source,
    )
}

function rewriteImportDeclarations(source, label, importMap) {
  const sourceFile = sourceFileFor(source, label)
  const used = new Set()
  const replacements = []

  sourceFile.forEachChild((node) => {
    if (!ts.isImportDeclaration(node) || !ts.isStringLiteral(node.moduleSpecifier)) return
    const specifier = node.moduleSpecifier.text
    const replacement = importMap[specifier]
    if (replacement) {
      used.add(specifier)
      replacements.push({
        start: node.moduleSpecifier.getStart(sourceFile) + 1,
        end: node.moduleSpecifier.getEnd() - 1,
        text: replacement,
      })
      return
    }

    if (specifier.startsWith('.') || specifier.startsWith('@/') || specifier.startsWith('@pancake/')) {
      throw new Error(`Cannot generate ${label}: unmapped source import ${specifier}`)
    }
  })

  const missing = Object.keys(importMap).filter((specifier) => !used.has(specifier))
  if (missing.length > 0) {
    throw new Error(`Cannot generate ${label}: missing expected source imports: ${missing.join(', ')}`)
  }

  return applyReplacements(source, replacements)
}

function dropImportDeclaration(source, label, specifier) {
  const sourceFile = sourceFileFor(source, label)
  let removed = false
  const replacements = []

  sourceFile.forEachChild((node) => {
    if (!ts.isImportDeclaration(node) || !ts.isStringLiteral(node.moduleSpecifier)) return
    if (node.moduleSpecifier.text !== specifier) return
    removed = true
    const lineEnd = source.indexOf('\n', node.getEnd())
    replacements.push({
      start: node.getFullStart(),
      end: lineEnd === -1 ? node.getEnd() : lineEnd + 1,
      text: '',
    })
  })

  if (!removed) {
    throw new Error(`Cannot generate ${label}: missing expected source import ${specifier}`)
  }

  const rewritten = applyReplacements(source, replacements)
  return rewritten.startsWith('\n') ? rewritten.slice(1) : rewritten
}

async function writeGenerated(rel, contents) {
  const filePath = path.join(ROOT, rel)
  const current = await read(rel).catch(() => null)
  if (current === contents) return false
  if (CHECK) {
    console.error(`${rel} is out of date. Run npm run generate:edge-shared.`)
    process.exitCode = 1
    return true
  }
  await writeFile(filePath, contents)
  return true
}

async function scoringCore() {
  const types = await read('core/src/scoring/types.ts')
  const formula = dropImportDeclaration(await read('core/src/scoring/formula.ts'), 'scoringCore', './types')
  return `${HEADER}${types}\n${formula}`
}

async function syncScores() {
  const source = rewriteImportDeclarations(await read('supabase/shared-src/sync/scores.ts'), 'syncScores', {
    '../lib/supabase': './supabase.ts',
    '../lib/scoring': './scoring.ts',
    '../lib/notifications': './notifications.ts',
    '../lib/nba': './nba.ts',
    '../lib/utils/date': './date.ts',
    '../types/database': './database.ts',
    './stats': './syncStats.ts',
    './scoreLineups': './scoreLineups.ts',
    './scoreShared': './scoreShared.ts',
  })
  return `${HEADER}${source}`
}

async function scoreLineups() {
  const source = rewriteImportDeclarations(await read('supabase/shared-src/sync/scoreLineups.ts'), 'scoreLineups', {
    '../lib/scoring': './scoring.ts',
    '../lib/nba': './nba.ts',
    '../lib/supabase': './supabase.ts',
    './scoreShared': './scoreShared.ts',
  })
  return `${HEADER}${source}`
}

async function scoreShared() {
  const source = rewriteImportDeclarations(await read('supabase/shared-src/sync/scoreShared.ts'), 'scoreShared', {
    '../lib/supabase': './supabase.ts',
  })
  return `${HEADER}${source}`
}

async function scheduleCore() {
  const source = rewriteImportDeclarations(await read('core/src/season/schedule.ts'), 'schedule', {
    './gameId': './gameId.ts',
  })
  return `${HEADER}${source}`
}

async function livePollCore() {
  const source = rewriteImportDeclarations(await read('core/src/sync/livePoll.ts'), 'livePoll', {
    '../dates': './date.ts',
  })
  return `${HEADER}${source}`
}

const outputs = [
  ['supabase/functions/_shared/date.ts', `${HEADER}${await read('core/src/dates/index.ts')}`],
  ['supabase/functions/_shared/gameId.ts', `${HEADER}${await read('core/src/season/gameId.ts')}`],
  ['supabase/functions/_shared/livePoll.ts', await livePollCore()],
  ['supabase/functions/_shared/schedule.ts', await scheduleCore()],
  ['supabase/functions/_shared/scoreLineups.ts', await scoreLineups()],
  ['supabase/functions/_shared/scoreShared.ts', await scoreShared()],
  ['supabase/functions/_shared/scoringCore.ts', await scoringCore()],
  ['supabase/functions/_shared/season.ts', `${HEADER}${await read('core/src/season/year.ts')}`],
  ['supabase/functions/_shared/syncScores.ts', await syncScores()],
]

let changed = false
for (const [rel, contents] of outputs) {
  if (rel.includes('/_shared/')) assertNoBackendImports(rel, contents)
  changed = await writeGenerated(rel, contents) || changed
}

if (!CHECK) {
  console.log(changed ? 'Generated Edge shared files.' : 'Edge shared files are already current.')
}
