import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { webkit } from 'playwright'
import { runWithScenarioResourceOwner } from './scenario-resource-owner.mjs'
import { resolvedTradeEnv } from './env.mjs'
import { setupTradeGameplayFixture, findAvailablePlayers } from './trade-fixture.mjs'

const env = resolvedTradeEnv()
for (const url of [env.supabaseUrl, env.apiBaseUrl, env.frontendUrl]) assert.equal(new URL(url).hostname, '127.0.0.1')
const output = process.env.E2E_BROWSER_ARTIFACT_DIR
assert.ok(output)
await mkdir(output, { recursive: true })
const check = result => { if (result.error) throw new Error(result.error.message); return result.data }
await runWithScenarioResourceOwner('trade legality WebKit', async () => {
const fixture = await setupTradeGameplayFixture(env, 0, { includeFuturePicks: false, isolatedPlayers: true })
const browser = await webkit.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
const page = await context.newPage()
page.setDefaultTimeout(20000)
const receipt = { engine: 'WebKit', width: 390, states: [], savedPlansWaitedForReview: false, executionHeldAndNotifiedBoth: false, finalRostersLegal: false, retainedTaxiExecuted: false }
const shot = async name => {
    await page.screenshot({ path: `${output}/${name}.png`, fullPage: true })
    receipt.states.push(name)
}
const signIn = async (index, expectedPlayer = index === 0 ? fixture.proposerPlayer.display_name : fixture.recipientPlayer.display_name) => {
    await page.goto(`${env.frontendUrl}/sign-in`)
    await page.locator('#root').getByPlaceholder('you@example.com').fill(fixture.users[index].email)
    await page.locator('#root').getByPlaceholder('Your password').fill(fixture.password)
    await page.locator('#root').getByRole('button', { name: 'Sign In', exact: true }).click()
    await page.waitForURL(url => url.pathname === '/')
    await page.getByRole('link', { name: 'Roster', exact: true }).first().click()
    await page.waitForURL(url => url.pathname === '/roster')
    await page.getByText(expectedPlayer, { exact: true }).first().waitFor()
}
try {
    const extra = await findAvailablePlayers(fixture.admin, fixture.league.id, fixture.currentSeason.id, 4, fixture.registerCreatedPlayer, { createOnly: true })
    check(await fixture.admin.from('leagues').update({ roster_size: 2, ir_slots: 1, taxi_slots: 0, allow_inactive_trades: true, trade_veto_mode: 'commissioner', trade_veto_window_hours: 24 }).eq('id', fixture.league.id))
    check(await fixture.admin.from('players').update({ injury_status: 'Out' }).in('id', [fixture.proposerPlayer.id, fixture.recipientPlayer.id, extra[0].id]))
    check(await fixture.admin.from('roster_players').update({ is_on_ir: true }).eq('league_id', fixture.league.id))
    check(await fixture.admin.from('roster_players').insert(extra.map((player, index) => ({ league_id: fixture.league.id, league_season_id: fixture.currentSeason.id, member_id: index < 2 ? fixture.proposer.id : fixture.recipient.id, player_id: player.id, acquired_via: 'draft' }))))
    const initialRosters = check(await fixture.admin.from('roster_players').select('member_id,player_id,is_on_ir,is_on_taxi').eq('league_season_id', fixture.currentSeason.id).order('player_id'))
    await signIn(0)
    await page.goto(`${env.frontendUrl}/propose-trade?recipientMemberId=${fixture.recipient.id}`)
    await page.getByTestId(`trade-sender-${fixture.recipient.id}`).click()
    await page.getByTestId(`trade-${fixture.recipient.id}-player-${fixture.recipientPlayer.id}`).click()
    await page.getByTestId(`trade-sender-${fixture.proposer.id}`).click()
    await page.getByTestId(`trade-${fixture.proposer.id}-player-${fixture.proposerPlayer.id}`).click()
    await page.getByTestId('trade-submit').click()
    await page.getByTestId('trade-confirm-submit').click()
    await page.getByText(/from IR does not free a Regular slot/).first().waitFor()
    assert.equal(check(await fixture.admin.from('trades').select('id').eq('league_id', fixture.league.id)).length, 0)
    assert.ok((await page.locator('body').innerText()).includes(fixture.proposerPlayer.display_name))
    assert.ok((await page.locator('body').innerText()).includes(fixture.recipientPlayer.display_name))
    await shot('01-invalid-submit-draft-intact')
    await page.getByLabel(`${extra[0].display_name}: ir`, { exact: true }).click()
    await page.getByLabel(`${fixture.proposerPlayer.display_name}: ir`, { exact: true }).click()
    await page.getByText('Roster ready', { exact: true }).first().waitFor()
    await shot('02-sender-plan-ready')
    await page.getByTestId('trade-confirm-submit').click()
    await page.waitForURL(url => !url.pathname.includes('propose-trade'))
    const [offer] = check(await fixture.admin.from('trades').select('id').eq('league_id', fixture.league.id))
    assert.ok(offer)
    const senderPlan = check(await fixture.admin.from('trade_participants').select('roster_moves').eq('trade_id', offer.id).eq('member_id', fixture.proposer.id).single())
    assert.deepEqual(senderPlan.roster_moves, [{ playerId: extra[0].id, destination: 'ir' }])
    check(await fixture.admin.from('players').update({ injury_status: null }).eq('id', fixture.proposerPlayer.id))
    await context.clearCookies()
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
    await signIn(1)
    await page.goto(`${env.frontendUrl}/trades`)
    await page.getByTestId(`trade-details-${offer.id}`).click()
    await page.getByLabel(`Accept trade with ${fixture.proposer.team_name}`, { exact: true }).click()
    await page.getByText('Make it legal', { exact: true }).waitFor()
    await page.getByText(/cannot use IR/).first().waitFor()
    await shot('03-accept-needs-ir-fix')
    await page.getByLabel(`${fixture.proposerPlayer.display_name}: active`, { exact: true }).click()
    await page.getByLabel(`Drop ${extra[2].display_name} at completion`, { exact: true }).click()
    await page.getByText('Ready for review. Nothing moves yet.', { exact: true }).waitFor()
    await shot('04-accept-plan-ready')
    await page.getByRole('button', { name: 'Confirm', exact: true }).click()
    await page.getByText('Roster choices saved. Waiting for review and execution.', { exact: true }).waitFor()
    assert.equal(check(await fixture.admin.from('trades').select('status').eq('id', offer.id).single()).status, 'accepted')
    assert.deepEqual(check(await fixture.admin.from('roster_players').select('member_id,player_id,is_on_ir,is_on_taxi').eq('league_season_id', fixture.currentSeason.id).order('player_id')), initialRosters)
    await page.goto(`${env.frontendUrl}/trades?tab=history`)
    await page.getByTestId(`trade-details-${offer.id}`).click()
    await page.getByText(/Veto window closes/).first().waitFor()
    await shot('05-accepted-awaiting-review')
    check(await fixture.admin.from('trades').update({ veto_window_expires_at: new Date(Date.now() - 60000).toISOString() }).eq('id', offer.id))
    check(await fixture.admin.from('players').update({ injury_status: null }).eq('id', extra[0].id))
    check(await fixture.admin.rpc('complete_accepted_trade_atomic', { p_trade_id: offer.id }))
    const held = check(await fixture.admin.from('trades').select('status,legality_issues').eq('id', offer.id).single())
    assert.equal(held.status, 'accepted')
    assert.ok(held.legality_issues.some(reason => reason.rule === 'ir_eligibility'))
    assert.equal(check(await fixture.admin.from('notification_outbox').select('member_id').eq('event_type', 'trade_needs_attention').contains('data', { tradeId: offer.id })).length, 2)
    await page.goto(`${env.frontendUrl}/trades?tab=history`)
    await page.getByTestId(`trade-details-${offer.id}`).click()
    await page.getByText('Needs attention', { exact: true }).waitFor()
    await shot('06-execution-held')
    check(await fixture.admin.from('players').update({ injury_status: 'Out' }).eq('id', extra[0].id))
    check(await fixture.admin.rpc('complete_accepted_trade_atomic', { p_trade_id: offer.id }))
    const rosters = check(await fixture.admin.from('roster_players').select('member_id,player_id,is_on_ir,is_on_taxi').eq('league_season_id', fixture.currentSeason.id))
    assert.ok(rosters.some(row => row.player_id === extra[0].id && row.is_on_ir))
    assert.ok(!rosters.some(row => row.player_id === extra[2].id))
    for (const member of [fixture.proposer.id, fixture.recipient.id]) assert.equal(rosters.filter(row => row.member_id === member && !row.is_on_ir && !row.is_on_taxi).length, 2)
    await page.goto(`${env.frontendUrl}/roster`)
    await page.getByText(fixture.proposerPlayer.display_name, { exact: true }).first().waitFor()
    await shot('07-executed-roster')
    check(await fixture.admin.from('leagues').update({ taxi_slots: 2 }).eq('id', fixture.league.id))
    check(await fixture.admin.from('players').update({ years_exp: 0, career_regular_season_games: 0 }).in('id', [fixture.recipientPlayer.id, extra[3].id]))
    await page.goto(`${env.frontendUrl}/propose-trade?recipientMemberId=${fixture.proposer.id}`)
    await page.getByTestId(`trade-sender-${fixture.proposer.id}`).click()
    await page.getByTestId(`trade-${fixture.proposer.id}-player-${fixture.recipientPlayer.id}`).click()
    await page.getByTestId(`trade-sender-${fixture.recipient.id}`).click()
    await page.getByTestId(`trade-${fixture.recipient.id}-player-${fixture.proposerPlayer.id}`).click()
    await page.getByTestId('trade-submit').click()
    await page.getByLabel(`${fixture.recipientPlayer.display_name}: taxi`, { exact: true }).click()
    await page.getByLabel(`${extra[3].display_name}: taxi`, { exact: true }).click()
    await page.getByText('Roster ready', { exact: true }).first().waitFor()
    await shot('08-incoming-taxi-destination')
    await page.getByTestId('trade-confirm-submit').click()
    await page.waitForURL(url => !url.pathname.includes('propose-trade'))
    const destination = check(await fixture.admin.from('trade_items').select('to_taxi').eq('player_id', fixture.recipientPlayer.id).eq('to_member_id', fixture.recipient.id).neq('trade_id', offer.id).single())
    assert.equal(destination.to_taxi, true)
    const second = check(await fixture.admin.from('trades').select('id').eq('league_id', fixture.league.id).neq('id', offer.id).single())
    const beforeSecondAcceptance = check(await fixture.admin.from('roster_players').select('member_id,player_id,is_on_ir,is_on_taxi').eq('league_season_id', fixture.currentSeason.id).order('player_id'))
    await context.clearCookies()
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
    await signIn(0, fixture.recipientPlayer.display_name)
    await page.goto(`${env.frontendUrl}/trades`)
    await page.getByTestId(`trade-details-${second.id}`).click()
    await page.getByLabel(`Accept trade with ${fixture.recipient.team_name}`, { exact: true }).click()
    await page.getByText('Ready for review. Nothing moves yet.', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Confirm', exact: true }).click()
    await page.getByText('Roster choices saved. Waiting for review and execution.', { exact: true }).waitFor()
    assert.deepEqual(check(await fixture.admin.from('roster_players').select('member_id,player_id,is_on_ir,is_on_taxi').eq('league_season_id', fixture.currentSeason.id).order('player_id')), beforeSecondAcceptance)
    check(await fixture.admin.from('trades').update({ veto_window_expires_at: new Date(Date.now() - 60000).toISOString() }).eq('id', second.id))
    check(await fixture.admin.rpc('complete_accepted_trade_atomic', { p_trade_id: second.id }))
    const secondRosters = check(await fixture.admin.from('roster_players').select('member_id,player_id,is_on_ir,is_on_taxi').eq('league_season_id', fixture.currentSeason.id))
    for (const playerId of [fixture.recipientPlayer.id, extra[3].id]) {
        assert.ok(secondRosters.some(row => row.player_id === playerId && row.member_id === fixture.recipient.id && row.is_on_taxi))
    }
    assert.equal(check(await fixture.admin.from('trades').select('status').eq('id', second.id).single()).status, 'completed')
    await context.clearCookies()
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
    await signIn(1)
    await page.getByRole('heading', { name: 'Taxi squad', exact: true }).evaluate(element => element.scrollIntoView({ block: 'start' }))
    await shot('09-retained-and-incoming-taxi-executed')
    receipt.retainedTaxiExecuted = true
    receipt.savedPlansWaitedForReview = true
    receipt.executionHeldAndNotifiedBoth = true
    receipt.finalRostersLegal = true
    await writeFile(`${output}/receipt.json`, JSON.stringify(receipt, null, 2))
    process.stdout.write(JSON.stringify(receipt) + '\n')
} catch (error) {
    await shot('failure').catch(() => {})
    await writeFile(`${output}/failure.txt`, String(error) + '\n' + await page.locator('body').innerText().catch(() => ''))
    throw error
} finally {
    await context.close()
    await browser.close()
    await fixture.dispose()
}

})
