BEGIN;
DELETE FROM private.work_items;
CREATE TEMP TABLE queue_checks(label text PRIMARY KEY,passed boolean NOT NULL CHECK(passed));
CREATE FUNCTION pg_temp.check_queue(p_label text,p_passed boolean) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF p_passed IS DISTINCT FROM true THEN RAISE EXCEPTION 'FAIL: %',p_label; END IF;
  INSERT INTO queue_checks VALUES(p_label,true);
END;
$$;
DO $$
DECLARE v_id bigint; v_token uuid; v_old uuid; v_count integer; v_invocation uuid:=gen_random_uuid(); v_retry timestamptz;
BEGIN
  v_id:=private.work_enqueue('player-stats-hints','one');
  PERFORM pg_temp.check_queue('duplicate enqueue is suppressed',private.work_enqueue('player-stats-hints','one') IS NULL);
  SELECT lease_token INTO v_token FROM private.work_claim();
  PERFORM pg_temp.check_queue('claim increments one attempt',(SELECT attempts=1 AND status='running' FROM private.work_items WHERE id=v_id));
  PERFORM pg_temp.check_queue('a live lease excludes another claim',NOT EXISTS(SELECT 1 FROM private.work_claim()));
  UPDATE private.work_items SET invocation_key=v_invocation WHERE id=v_id;
  PERFORM pg_temp.check_queue('heartbeat renews the current lease',public.renew_work_lease(v_invocation));
  PERFORM pg_temp.check_queue('wrong heartbeat fails',NOT public.renew_work_lease(gen_random_uuid()));
  PERFORM pg_temp.check_queue('wrong completion token fails',NOT private.work_finish(v_id,gen_random_uuid()));
  PERFORM pg_temp.check_queue('success completes',private.work_finish(v_id,v_token));
  PERFORM pg_temp.check_queue('duplicate completion is ignored',NOT private.work_finish(v_id,v_token));
  PERFORM pg_temp.check_queue('success emits one event',(SELECT count(*)=1 FROM public.league_events WHERE detail->>'work_id'=v_id::text AND kind='work.succeeded'));
  v_id:=private.work_enqueue('player-stats-hints','crashed');
  SELECT lease_token INTO v_token FROM private.work_claim();
  v_old:=v_token;
  UPDATE private.work_items SET lease_until=now()-interval '1 second' WHERE id=v_id;
  PERFORM pg_temp.check_queue('expired heartbeat fails',NOT public.renew_work_lease(v_invocation));
  PERFORM private.work_claim();
  PERFORM pg_temp.check_queue('expired lease schedules one retry',(SELECT status='failed' AND attempts=1 AND due_at=now()+interval '60 seconds' FROM private.work_items WHERE id=v_id));
  PERFORM private.work_claim();
  PERFORM pg_temp.check_queue('repeat recovery does not add attempts',(SELECT attempts=1 FROM private.work_items WHERE id=v_id));
  UPDATE private.work_items SET due_at=now() WHERE id=v_id;
  SELECT lease_token INTO v_token FROM private.work_claim();
  PERFORM pg_temp.check_queue('retry fences the old worker',v_token<>v_old AND NOT private.work_finish(v_id,v_old));
  PERFORM private.work_finish(v_id,v_token,'failure two');
  PERFORM pg_temp.check_queue('second failure backs off two minutes',(SELECT due_at=now()+interval '120 seconds' FROM private.work_items WHERE id=v_id));
  UPDATE private.work_items SET due_at=now() WHERE id=v_id;
  SELECT lease_token INTO v_token FROM private.work_claim();
  PERFORM private.work_finish(v_id,v_token,'failure three');
  PERFORM pg_temp.check_queue('three failures dead-letter',(SELECT attempts=3 AND status='dead' AND last_error='failure three' FROM private.work_items WHERE id=v_id));
  PERFORM pg_temp.check_queue('dead letter emits one event',(SELECT count(*)=1 FROM public.league_events WHERE detail->>'work_id'=v_id::text AND kind='work.dead'));
  v_id:=private.work_enqueue('player-stats-hints','healthy');
  SELECT lease_token INTO v_token FROM private.work_claim();
  PERFORM pg_temp.check_queue('dead letter does not block healthy work',v_token IS NOT NULL);
  PERFORM private.work_execute(v_id,v_token);
  PERFORM pg_temp.check_queue('SQL worker completes',(SELECT status='succeeded' FROM private.work_items WHERE id=v_id));
  PERFORM pg_temp.check_queue('dashboard counts dead and running separately',(SELECT dead=1 AND running=0 FROM public.work_dashboard() WHERE kind='player-stats-hints'));
  v_id:=private.work_enqueue('player-stats-hints','fenced');
  SELECT lease_token INTO v_token FROM private.work_claim();
  v_invocation:=gen_random_uuid();
  UPDATE private.work_items SET invocation_key=v_invocation WHERE id=v_id;
  PERFORM set_config('request.headers',jsonb_build_object('x-pancake-work-key',v_invocation)::text,true);
  UPDATE public.players SET first_name=first_name WHERE false;
  PERFORM set_config('request.headers','{}',true);
  UPDATE private.work_items SET lease_until=now()-interval '1 second' WHERE id=v_id;
  PERFORM set_config('request.headers',jsonb_build_object('x-pancake-work-key',v_invocation)::text,true);
  BEGIN
    UPDATE public.players SET first_name=first_name WHERE false;
    RAISE EXCEPTION 'Expired worker reaches a write' USING ERRCODE='XX000';
  EXCEPTION WHEN SQLSTATE 'PT409' THEN NULL; END;
  PERFORM set_config('request.headers','{}',true);
  PERFORM pg_temp.check_queue('expired worker is fenced before writes',true);
  PERFORM private.work_claim(0);
  UPDATE private.work_items SET due_at=now() WHERE id=v_id;
  SELECT lease_token INTO v_token FROM private.work_claim();
  UPDATE private.work_items SET invocation_key=gen_random_uuid() WHERE id=v_id;
  PERFORM set_config('request.headers',jsonb_build_object('x-pancake-work-key',v_invocation)::text,true);
  BEGIN
    UPDATE public.players SET first_name=first_name WHERE false;
    RAISE EXCEPTION 'Displaced worker reaches a write' USING ERRCODE='XX000';
  EXCEPTION WHEN SQLSTATE 'PT409' THEN NULL; END;
  PERFORM set_config('request.headers','{}',true);
  PERFORM pg_temp.check_queue('displaced worker is fenced before writes',true);
  PERFORM private.work_finish(v_id,v_token);
  PERFORM set_config('app.supabase_url','http://127.0.0.1:1',true);
  PERFORM set_config('app.edge_internal_token','queue-outcome-test',true);
  v_id:=private.work_enqueue('sync-players','correlated');
  SELECT lease_token INTO v_token FROM private.work_claim();
  PERFORM private.work_execute(v_id,v_token);
  SELECT invocation_key INTO v_invocation FROM private.work_items WHERE id=v_id;
  PERFORM pg_temp.check_queue('dispatch binds the lease to its invocation',v_invocation IS NOT NULL);
  PERFORM public.start_edge_invocation(v_invocation,'sync-players');
  PERFORM public.finish_edge_invocation(v_invocation,'success');
  PERFORM pg_temp.check_queue('worker outcome completes queue work',(SELECT status='succeeded' FROM private.work_items WHERE id=v_id));
  PERFORM public.finish_edge_invocation(v_invocation,'success');
  PERFORM pg_temp.check_queue('repeated worker outcome emits once',(SELECT count(*)=1 FROM public.league_events WHERE detail->>'work_id'=v_id::text));
  INSERT INTO private.work_kinds(kind) VALUES('synthetic-failure');
  v_id:=private.work_enqueue('synthetic-failure','isolated');
  PERFORM private.work_enqueue('player-stats-hints','after-error');
  PERFORM public.dispatch_work();
  PERFORM pg_temp.check_queue('one worker error schedules its own retry',(SELECT status='failed' AND attempts=1 FROM private.work_items WHERE id=v_id));
  PERFORM pg_temp.check_queue('one worker error does not roll back healthy work',(SELECT status='succeeded' FROM private.work_items WHERE kind='player-stats-hints' AND key='after-error'));
  PERFORM pg_temp.check_queue('only the dispatcher is scheduled',(SELECT count(*)=1 AND bool_and(jobname='work-dispatcher' AND schedule='* * * * *') FROM cron.job WHERE jobname NOT IN ('io-hint-drain','io-cron-history-retention')));
END;
$$;
SELECT count(*) AS passed_checks FROM queue_checks;
ROLLBACK;
