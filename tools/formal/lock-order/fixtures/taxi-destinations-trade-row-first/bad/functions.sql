CREATE OR REPLACE FUNCTION private.roster_status_game_started(p_player_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SET search_path = public
AS $$
  WITH slate AS (
    SELECT (now() AT TIME ZONE 'America/New_York')::date AS today
  )
  SELECT EXISTS (
    SELECT 1
      FROM players AS p
      JOIN nba_games AS g ON g.home_team = p.nba_team OR g.away_team = p.nba_team
      CROSS JOIN slate
     WHERE p.id = p_player_id
       AND g.game_date IN (slate.today - 1, slate.today)
       AND (
         g.status = 'InProgress'
         OR (g.game_date = slate.today AND g.status = 'Final')
         OR (g.game_time <= now() AND (g.game_date = slate.today OR g.game_time >= now() - interval '12 hours'))
         OR (g.started_at <= now() AND (g.game_date = slate.today OR g.started_at >= now() - interval '12 hours'))
       )
  )
$$;

CREATE OR REPLACE FUNCTION private.is_reserved_trade_asset(
  p_league_id uuid,
  p_league_season_id uuid,
  p_member_id uuid,
  p_player_id uuid DEFAULT NULL,
  p_pick_id uuid DEFAULT NULL,
  p_exclude_trade_id uuid DEFAULT NULL
)
RETURNS boolean
LANGUAGE sql
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
      FROM trade_items AS item
      JOIN trades AS trade
        ON trade.id = item.trade_id
       AND trade.status = 'accepted'::trade_status
     WHERE trade.league_id = p_league_id
       AND (p_league_season_id IS NULL OR trade.league_season_id = p_league_season_id)
       AND (p_exclude_trade_id IS NULL OR trade.id <> p_exclude_trade_id)
       AND item.from_member_id = p_member_id
       AND (
         (p_player_id IS NOT NULL AND item.player_id = p_player_id)
         OR (p_pick_id IS NOT NULL AND item.pick_id = p_pick_id)
       )
  )
$$;

CREATE OR REPLACE FUNCTION private.reserved_trade_asset_message()
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT 'This asset is reserved by an accepted trade.'
$$;
