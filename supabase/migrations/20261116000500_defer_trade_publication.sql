CREATE OR REPLACE FUNCTION private.publish_trade_changes(p_publication_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE publication private.trade_publications%ROWTYPE; event jsonb; topic text; source text;
  previous_mode text:=coalesce(current_setting('pancake.trade_write',true),'');
BEGIN
  SELECT * INTO publication FROM private.trade_publications WHERE id=p_publication_id FOR UPDATE SKIP LOCKED;
  IF NOT FOUND THEN
    IF EXISTS(SELECT 1 FROM private.trade_publications WHERE id=p_publication_id) THEN
      RAISE EXCEPTION 'Trade publication is busy.' USING ERRCODE='55P03';
    END IF;
    RETURN;
  END IF;
  IF NOT EXISTS(SELECT 1 FROM public.leagues WHERE id=publication.league_id AND deleted_at IS NULL) THEN
    DELETE FROM private.trade_publications WHERE id=publication.id;
    RETURN;
  END IF;
  PERFORM set_config('pancake.trade_write','',true);
  FOR event IN SELECT value FROM jsonb_array_elements(publication.events) LOOP
    INSERT INTO public.league_events(league_id,member_id,kind,summary,detail,created_at)
      VALUES(publication.league_id,(SELECT id FROM public.league_members WHERE id=(event->>'member_id')::uuid),
        event->>'kind',event->>'summary',event->'detail',(event->>'created_at')::timestamptz);
  END LOOP;
  FOREACH topic IN ARRAY publication.topics LOOP
    FOREACH source IN ARRAY publication.sources LOOP
      PERFORM private.league_version_enqueue(publication.league_id,topic,source);
    END LOOP;
  END LOOP;
  PERFORM private.refresh_queue_screen_views(publication.league_id);
  DELETE FROM private.trade_publications WHERE id=publication.id;
  PERFORM set_config('pancake.trade_write',previous_mode,true);
END;
$$;

CREATE OR REPLACE FUNCTION private.league_version_enqueue(p_league_id uuid,p_topic text,p_source text)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF current_setting('pancake.trade_write',true)='true' THEN
    PERFORM private.queue_trade_publication(p_league_id,p_topic,p_source);
    RETURN;
  END IF;
  INSERT INTO private.league_version_pending AS pending(transaction_id,league_id,topics,sources)
    VALUES(pg_current_xact_id(),p_league_id,ARRAY[p_topic],ARRAY[p_source])
  ON CONFLICT(transaction_id,league_id) DO UPDATE SET
    topics=ARRAY(SELECT DISTINCT unnest(pending.topics||EXCLUDED.topics) ORDER BY 1),
    sources=ARRAY(SELECT DISTINCT unnest(pending.sources||EXCLUDED.sources) ORDER BY 1)
  WHERE NOT pending.topics @> EXCLUDED.topics OR NOT pending.sources @> EXCLUDED.sources;
END;
$$;

CREATE OR REPLACE FUNCTION private.refresh_changed_screen_views()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE row_data jsonb;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  IF TG_TABLE_NAME<>'league_change_hints' AND current_setting('pancake.trade_write',true)='true' THEN
    PERFORM private.queue_trade_publication(
      CASE WHEN TG_TABLE_NAME='leagues' THEN (row_data->>'id')::uuid ELSE (row_data->>'league_id')::uuid END);
    RETURN NULL;
  END IF;
  IF TG_TABLE_NAME = 'league_change_hints' AND row_data->>'topic' = 'version'
    AND jsonb_array_length(COALESCE(row_data->'details'->0->'scope'->'tables', '[]')) > 0
    AND row_data->'details'->0->'scope'->'tables' <@ '["standings_current","matchup_totals","player_season_averages","trade_value_cache"]'::jsonb THEN
    RETURN NULL;
  END IF;
  PERFORM private.refresh_queue_screen_views(
    CASE WHEN TG_TABLE_NAME = 'leagues' THEN (row_data->>'id')::uuid ELSE (row_data->>'league_id')::uuid END);
  RETURN NULL;
END;
$$;

